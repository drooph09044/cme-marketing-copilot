function groupJourneys(journeys) {
  const categories = [];
  for (const journey of journeys) {
    const categoryId = journey.categoryId ?? journey.category?.categoryId;
    const categoryName = journey.categoryName ?? journey.category?.categoryName;
    const categoryDescription = journey.categoryDescription ?? journey.category?.categoryDescription;
    let category = categories.find((entry) => entry.id === categoryId);
    if (!category) {
      category = {
        id: categoryId,
        name: categoryName,
        description: categoryDescription,
        journeys: [],
      };
      categories.push(category);
    }
    category.journeys.push({ ...journey });
  }
  return { categories };
}

export default groupJourneys(PRESET_JOURNEYS);
